use std::collections::{BTreeMap, BTreeSet};
use std::path::Path;

use anyhow::{Result, bail};

use crate::components::ComponentMap;
use crate::config::{Config, DEFAULT_CONFIG};
use crate::{check, lang, report, scan};

/// Directories whose children are the components, in order of preference. They are
/// layouts shared across ecosystems (`src`, monorepos' `packages` and `apps`), not
/// what one language knows, and the order decides between them, so they stay here
/// rather than in the registry.
const SOURCE_ROOTS: &[&str] = &[
    "internal", "src", "app", "lib", "packages", "apps", "services", "pkg",
];

/// Top-level directories that are never components of their own, whatever the
/// language; those a language's toolchain fills come from the registry.
const NOT_COMPONENTS: &[&str] = &[
    "dist",
    "out",
    "test",
    "tests",
    "spec",
    "docs",
    "doc",
    "examples",
    "scripts",
    "tools",
    "migrations",
];

/// A component found in the layout of the project: its name and `in` pattern.
#[derive(Debug, PartialEq, Eq)]
pub struct Found {
    pub name: String,
    pub pattern: String,
}

/// Components from the layout of `files` (relative, `/`-separated): the
/// subdirectories of the first conventional source root that has at least two,
/// otherwise the top-level directories.
pub fn discover(files: &[String]) -> Vec<Found> {
    let dirs_under = |base: &str| -> BTreeSet<String> {
        files
            .iter()
            .filter_map(|f| {
                let rest = if base.is_empty() {
                    f.as_str()
                } else {
                    f.strip_prefix(base)?.strip_prefix('/')?
                };
                let (dir, _) = rest.split_once('/')?;
                Some(dir.to_string())
            })
            .collect()
    };
    for base in SOURCE_ROOTS {
        let dirs = dirs_under(base);
        if dirs.len() >= 2 {
            return named(dirs.into_iter().map(|d| (format!("{base}/{d}"), d)));
        }
    }
    named(
        dirs_under("")
            .into_iter()
            .filter(|d| {
                !d.starts_with('.')
                    && !NOT_COMPONENTS.contains(&d.as_str())
                    && !lang::registry::is_toolchain_dir(d)
            })
            .map(|d| (d.clone(), d)),
    )
}

/// A component for each `(pattern, directory)`, named after the directory without
/// the characters that make a name read as a glob or a set in a list of components
/// (`@acme` is `acme`); a directory whose name is left empty, or taken, is none.
fn named(dirs: impl Iterator<Item = (String, String)>) -> Vec<Found> {
    let mut taken = BTreeSet::new();
    dirs.filter_map(|(pattern, dir)| {
        let name: String = dir
            .chars()
            .filter(|c| !matches!(c, '@' | '*' | '?' | '[' | ']' | '{' | '}'))
            .collect();
        (!name.is_empty() && taken.insert(name.clone())).then_some(Found { name, pattern })
    })
    .collect()
}

/// A YAML key or scalar, quoted when plain style would be read as something else.
fn scalar(text: &str) -> String {
    let plain = text
        .chars()
        .next()
        .is_some_and(|c| c.is_ascii_alphabetic() || c == '_')
        && text
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '-' || c == '/' || c == '.')
        && !matches!(
            text.to_ascii_lowercase().as_str(),
            "true" | "false" | "null" | "yes" | "no" | "on" | "off" | "y" | "n"
        );
    if plain {
        text.to_string()
    } else {
        serde_json::to_string(text).expect("a string serializes")
    }
}

/// The config text: every dependency between components found in the code is allowed.
pub fn render(found: &[Found], deps: &BTreeMap<String, BTreeSet<String>>) -> String {
    let mut out = String::from(
        "# yaml-language-server: $schema=https://raw.githubusercontent.com/mokevnin/easement/main/easement.schema.json\n\
         # Generated by `easement init` from the code as it is: every dependency found\n\
         # between components is allowed. Delete the ones that should not exist and add\n\
         # `because:` reasons, then run `easement check`.\n\
         version: 1\n\ncomponents:\n",
    );
    for f in found {
        out.push_str(&format!(
            "  {}: {{ in: {} }}\n",
            scalar(&f.name),
            scalar(&f.pattern)
        ));
    }
    if !deps.is_empty() {
        out.push_str("\nrules:\n");
        for (from, to) in deps {
            let list: Vec<String> = to.iter().map(|t| scalar(t)).collect();
            out.push_str(&format!(
                "  {}: {{ may_depend_on: [{}] }}\n",
                scalar(from),
                list.join(", ")
            ));
        }
    }
    out.push_str("\n# no_cycles: true\n# strict: true\n");
    out
}

/// Writes a starting `easement.yml` into `root` and says what it contains,
/// reading the indexes through `cache`.
pub fn run(root: &Path, force: bool, cache: &mut scan::Cache) -> Result<String> {
    let path = root.join(DEFAULT_CONFIG);
    if path.exists() && !force {
        bail!(
            "{} already exists (use --force to overwrite)",
            path.display()
        );
    }
    // (path, whether it is a file): the adapters read links too.
    let walked: Vec<(std::path::PathBuf, bool)> = crate::relpath::walker(root)
        .build()
        .flatten()
        .filter(|e| e.file_type().is_some_and(|t| !t.is_dir()))
        .filter_map(|e| {
            let is_file = e.file_type().is_some_and(|t| t.is_file());
            Some((crate::relpath::relative(root, e.path())?, is_file))
        })
        .collect();
    let targets: Vec<std::path::PathBuf> = walked.iter().map(|(p, _)| p.clone()).collect();
    let adapters = lang::adapters::build(root, &targets)?;
    let files: Vec<String> = walked
        .iter()
        .filter(|(_, is_file)| *is_file)
        .map(|(p, _)| crate::relpath::slash(p))
        .filter(|p| crate::indexer::indexed(p) || adapters.iter().any(|a| a.handles(Path::new(p))))
        .collect();
    let found = discover(&files);
    if found.is_empty() {
        bail!("found no source directories to turn into components; write easement.yml by hand");
    }
    let draft = render(&found, &BTreeMap::new());
    let config: Config = serde_norway::from_str(&draft)?;
    let scanned = scan::scan(root, &config.scan_policy(), cache)?;
    let map = ComponentMap::new(&config)?;
    let (_, edges, _) = check::evaluate(&config, &map, &scanned.deps);
    let mut deps: BTreeMap<String, BTreeSet<String>> = BTreeMap::new();
    for e in &edges {
        deps.entry(e.from.clone()).or_default().insert(e.to.clone());
    }
    std::fs::write(&path, render(&found, &deps))?;
    let mut out = format!(
        "easement: wrote {} with {} components and {} allowed dependencies; \
         remove the dependencies that should not exist, then run `easement check`",
        path.display(),
        found.len(),
        deps.values().map(BTreeSet::len).sum::<usize>()
    );
    // The allowances come from the graph: what it could not read, they leave out.
    let stats = check::Stats {
        uncovered: scanned.uncovered.clone(),
        unavailable: scanned.unavailable.clone(),
        ..check::Stats::default()
    };
    let gaps = report::gap_lines(
        &report::graph_gaps(&stats, &scanned.uncovered),
        &[],
        "the allowances leave out what this code depends on",
        false,
        false,
    );
    if !gaps.is_empty() {
        out.push_str(&format!("\n{}", gaps.trim_end()));
    }
    if let Some(note) = report::cache_note_of(scanned.from_cache) {
        out.push_str(&format!("\neasement: {note}"));
    }
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn files(paths: &[&str]) -> Vec<String> {
        paths.iter().map(|p| p.to_string()).collect()
    }

    fn names(found: &[Found]) -> Vec<(&str, &str)> {
        found
            .iter()
            .map(|f| (f.name.as_str(), f.pattern.as_str()))
            .collect()
    }

    #[test]
    fn prefers_a_source_root_with_several_children() {
        let found = discover(&files(&[
            "cmd/app/main.go",
            "internal/handlers/a.go",
            "internal/services/b.go",
            "internal/main.go",
            "src/only/c.go",
        ]));
        assert_eq!(
            names(&found),
            [
                ("handlers", "internal/handlers"),
                ("services", "internal/services")
            ]
        );
    }

    #[test]
    fn falls_back_to_top_level_directories() {
        let found = discover(&files(&[
            "api/a.py",
            "billing/b.py",
            "tests/t.py",
            ".venv/x.py",
            "setup.py",
        ]));
        assert_eq!(names(&found), [("api", "api"), ("billing", "billing")]);
        assert!(discover(&files(&["main.go"])).is_empty());
    }

    /// A directory some language's toolchain fills, as the registry lists them
    /// (C#'s `bin` and `obj`, Go's `testdata`, npm's `node_modules`), is no
    /// component, whichever language the project is in.
    #[test]
    fn a_directory_a_toolchain_fills_is_no_component() {
        let found = discover(&files(&[
            "api/a.cs",
            "billing/b.cs",
            "bin/Debug/app.dll.cs",
            "obj/project.assets.cs",
            "testdata/case.go",
            "node_modules/x/index.ts",
            "vendor/autoload.php",
        ]));
        assert_eq!(names(&found), [("api", "api"), ("billing", "billing")]);
    }

    /// A directory such as `@acme` or `[id]` would make a name that reads as a set
    /// or a glob in a list of components, which a policy refuses: the name keeps
    /// its other characters, and the pattern the directory.
    #[test]
    fn names_a_component_after_a_directory_without_glob_or_set_characters() {
        let found = discover(&files(&[
            "packages/@acme/a.ts",
            "packages/[id]/b.ts",
            "packages/web/c.ts",
        ]));
        assert_eq!(
            names(&found),
            [
                ("acme", "packages/@acme"),
                ("id", "packages/[id]"),
                ("web", "packages/web")
            ]
        );
    }

    #[test]
    fn renders_valid_config_with_quoting() {
        let found = [
            Found {
                name: "web".into(),
                pattern: "src/web".into(),
            },
            Found {
                name: "no".into(),
                pattern: "src/no".into(),
            },
        ];
        let deps = BTreeMap::from([("web".to_string(), BTreeSet::from(["no".to_string()]))]);
        let text = render(&found, &deps);
        assert!(text.contains("  \"no\": { in: src/no }"));
        let config: Config = serde_norway::from_str(&text).unwrap();
        assert!(config.grant("web", "no").is_some());
        assert!(!config.grant("no", "web").is_some());
    }
}
